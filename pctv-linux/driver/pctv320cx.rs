/// The C glue holds a `void *` cookie; every callback recovers the driver
/// from it.
unsafe fn drv(cookie: *mut c_void) -> &'static mut Pctv320cxInner {
    &mut *(cookie as *mut Pctv320cxInner)
}

unsafe extern "C" fn op_get_fmt(cookie: *mut c_void, out: *mut bindings::pctv_fmt) -> c_int {
    let d = drv(cookie);
    *out = d.fmt;
    0
}

/// Clamp a requested format without touching the hardware.
unsafe fn clamp_fmt(std_sel: u32, fmt: &mut bindings::pctv_fmt) {
    let (lines_per_field, _) = geometry(std_sel);
    let height = (lines_per_field * 2) as u32;

    fmt.width = 720;
    fmt.height = height;
    fmt.bytesperline = ACTIVE_PIXEL_BYTES as u32;
    fmt.sizeimage = (ACTIVE_PIXEL_BYTES * lines_per_field * 2) as u32;
    fmt.field = PCTV_FIELD_INTERLACED;
    fmt.colorspace = if std_sel == STD_NTSC {
        PCTV_COLORSPACE_SMPTE170M
    } else {
        PCTV_COLORSPACE_470BG
    };
}

fn geometry(std_sel: u32) -> (usize, u32) {
    if std_sel == STD_NTSC {
        (NTSC_LINES, 30000)
    } else {
        (PAL_LINES, 25000)
    }
}

unsafe extern "C" fn op_validate_fmt(cookie: *mut c_void, fmt: *mut bindings::pctv_fmt) -> c_int {
    let d = drv(cookie);
    clamp_fmt(d.std_sel, &mut *fmt);
    0
}

unsafe extern "C" fn op_apply_fmt(cookie: *mut c_void, fmt: *const bindings::pctv_fmt) -> c_int {
    let d = drv(cookie);
    let mut f = *fmt;
    clamp_fmt(d.std_sel, &mut f);
    d.fmt = f;
    (*d.deframer.lock()).reset(d.std_sel);
    0
}

unsafe extern "C" fn op_get_input(cookie: *mut c_void, index: *mut u32) -> c_int {
    *index = drv(cookie).input;
    0
}

unsafe extern "C" fn op_set_input(cookie: *mut c_void, index: u32) -> c_int {
    let d = drv(cookie);
    if index >= INPUTS.len() as u32 {
        return -EINVAL;
    }
    d.input = index;
    if d.decoder_ready {
        d.input_setup(index);
    }
    0
}

unsafe extern "C" fn op_get_std(cookie: *mut c_void, std_sel: *mut u32) -> c_int {
    *std_sel = drv(cookie).std_sel;
    0
}

unsafe extern "C" fn op_set_std(cookie: *mut c_void, std_sel: u32) -> c_int {
    let d = drv(cookie);
    if std_sel != STD_PAL && std_sel != STD_NTSC {
        return -EINVAL;
    }
    d.std_sel = std_sel;
    if d.decoder_ready {
        d.std_setup(std_sel);
    }
    let (lines_per_field, _) = geometry(std_sel);
    clamp_fmt(std_sel, &mut d.fmt);
    d.fmt.height = (lines_per_field * 2) as u32;
    (*d.deframer.lock()).reset(std_sel);
    0
}

unsafe extern "C" fn op_set_ctrl(cookie: *mut c_void, id: u32, value: c_int) -> c_int {
    // Before the decoder is up there is nothing to write to; report success so
    // the control handler (and userspace) does not fail on a card whose
    // firmware is missing.
    if !drv(cookie).decoder_ready {
        return 0;
    }
    let d = drv(cookie);
    if !d.decoder_ready {
        return 0;
    }
    let ret = d.ctrl_apply(id, value);
    if ret < 0 && ret != -EINVAL {
        return ret;
    }
    0
}

unsafe extern "C" fn op_get_signal(cookie: *mut c_void, signal: *mut u32) -> c_int {
    let d = drv(cookie);
    *signal = if d.decoder_ready && d.signal_present() { 1 } else { 0 };
    0
}

unsafe extern "C" fn op_start_streaming(cookie: *mut c_void) -> c_int {
    drv(cookie).stream_start()
}

unsafe extern "C" fn op_stop_streaming(cookie: *mut c_void) {
    drv(cookie).stream_stop();
}

