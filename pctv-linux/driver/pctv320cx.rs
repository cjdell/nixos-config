const PCTV_FIELD_INTERLACED: u32 = 4;		/* V4L2_FIELD_INTERLACED */
const PCTV_COLORSPACE_SMPTE170M: u32 = 1;	/* V4L2_COLORSPACE_SMPTE170M */
const PCTV_COLORSPACE_470BG: u32 = 6;		/* V4L2_COLORSPACE_470_SYSTEM_BG */
const PCTV_STD_PAL_B: u64 = 0x00000001;		/* V4L2_STD_PAL_B */
const PCTV_STD_NTSC_M: u64 = 0x00001000;		/* V4L2_STD_NTSC_M */

