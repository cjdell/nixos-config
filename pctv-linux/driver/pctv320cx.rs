/// Bulk-IN endpoint of the streaming interface: the bridge exposes two bulk
/// IN endpoints (TS and analog), pick the 512-byte-packet one that is not the
/// firmware pipe.
unsafe fn find_bulk_in_ep(intf: *mut bindings::usb_interface) -> c_int {
    let alt = (*intf).cur_altsetting;
    if alt.is_null() {
        return -ENODEV;
    }
    let count = (*alt).desc.bNumEndpoints as usize;
    let eps = core::slice::from_raw_parts((*alt).endpoint, count);
    let mut first: c_int = -ENODEV;
    for ep in eps {
        if !bindings::pctv_usb_endpoint_is_in(&ep.desc) {
            continue;
        }
        if bindings::pctv_usb_endpoint_maxpkt(&ep.desc) as usize & 0x7ff != 512 {
            continue;
        }
        let num = bindings::pctv_usb_endpoint_num(&ep.desc);
        // The 320cx exposes three bulk-IN endpoints (0x81/0x82/0x83) and only
        // **EP 2 (0x82)** ever carries the capture stream - FINDINGS.md
        // section 11.2, and the in-tree dib0700 devices table (stream
        // endpoint 2).  Reading 0x81 simply never completes a URB.
        if num == CAPTURE_EP_NUM {
            return (num | 0x80) as c_int;
        }
        if first < 0 {
            first = (num | 0x80) as c_int;
        }
    }
    first
}

/// Static description of the device for the C glue.
fn glue_info() -> bindings::pctv_glue_info {
    bindings::pctv_glue_info {
        card: b"Pinnacle PCTV 320cx\0".as_ptr() as *const c_char,
        bus_info: b"usb-pctv320cx\0".as_ptr() as *const c_char,
        input_names: [
            b"Composite 1\0".as_ptr() as *const c_char,
            b"Composite 2\0".as_ptr() as *const c_char,
            b"Composite 3\0".as_ptr() as *const c_char,
            b"S-Video\0".as_ptr() as *const c_char,
        ],
        num_inputs: INPUTS.len() as u32,
        stds: (PCTV_STD_PAL_B | PCTV_STD_NTSC_M),
        caps: bindings::V4L2_CAP_VIDEO_CAPTURE | bindings::V4L2_CAP_STREAMING
            | bindings::V4L2_CAP_READWRITE,
    }
}

fn ops_table() -> bindings::pctv_ops {
    bindings::pctv_ops {
        drvdata: core::ptr::null_mut(),
        get_fmt: Some(op_get_fmt),
        validate_fmt: Some(op_validate_fmt),
        apply_fmt: Some(op_apply_fmt),
        get_input: Some(op_get_input),
        set_input: Some(op_set_input),
        get_std: Some(op_get_std),
        set_std: Some(op_set_std),
        set_ctrl: Some(op_set_ctrl),
        get_signal: Some(op_get_signal),
        start_streaming: Some(op_start_streaming),
        stop_streaming: Some(op_stop_streaming),
    }
}

unsafe fn probe(intf: *mut bindings::usb_interface) -> Result {
    let udev = bindings::pctv_interface_to_usbdev(intf);
    if udev.is_null() {
        return Err(Error::from_errno(-ENODEV));
    }
    let ep_in = find_bulk_in_ep(intf);
    if ep_in < 0 {
        kernel::pr_warn!("no bulk-IN endpoint found\n");
        return Err(Error::from_errno(ep_in));
    }

    let mut inner = KBox::pin_init(
        pin_init!(Pctv320cxInner {
            udev,
            intf,
            glue: core::ptr::null_mut(),
            ep_in: ep_in as u8,
            urbs: [const { Urb::empty() }; NUM_URBS],
            fw_buf: core::ptr::null_mut(),
            field_buf: core::ptr::null_mut(),
            streaming: Atomic::new(false),
            dropped: Atomic::new(0),
            deframer <- new_spinlock!(Deframer::new(), "pctv320cx-deframe"),
            std_sel: STD_PAL,
            input: 0,
            fmt: bindings::pctv_fmt {
                width: 720,
                height: (PAL_LINES * 2) as u32,
                bytesperline: ACTIVE_PIXEL_BYTES as u32,
                sizeimage: (ACTIVE_PIXEL_BYTES * PAL_LINES * 2) as u32,
                field: PCTV_FIELD_INTERLACED,
                colorspace: PCTV_COLORSPACE_470BG,
            },
            clock_on: false,
            decoder_ready: false,
        }),
        kernel::alloc::flags::GFP_KERNEL,
    )?;

    // The object is pinned by pin_init; the fields touched below are only
    // written before the object is published to the C glue, and the box is
    // never moved after that (it is leaked on success, freed on the error
    // paths below).
    let d = unsafe { inner.as_mut().get_unchecked_mut() };

    d.alloc_urbs()?;

    let cookie = d as *mut Pctv320cxInner as *mut c_void;
    let mut ops = ops_table();
    ops.drvdata = cookie;

    let glue = bindings::pctv_glue_create(intf, &glue_info(), &ops);
    if glue.is_null() {
        d.free_urbs();
        return Err(Error::from_errno(-ENOMEM));
    }
    d.glue = glue;

    // Bring the hardware up.  A failure here is not fatal to the binding: the
    // device node still appears, and the error is reported, so that a missing
    // firmware file is visible instead of leaving a silent card.
    let hw = probe_hardware(d);

    if bindings::pctv_glue_register(glue) < 0 {
        d.free_urbs();
        bindings::pctv_glue_destroy(glue);
        return Err(Error::from_errno(-ENOMEM));
    }

    bindings::pctv_dev_set_drvdata(
        &mut (*intf).dev as *mut bindings::device,
        cookie,
    );
    kernel::pr_info!("Pinnacle PCTV 320cx analog capture ready\n");
    if let Err(e) = hw {
        kernel::pr_warn!("analog bring-up incomplete - capture will stay dark\n");
        let _ = e;
    }

    // The box keeps the driver object alive until disconnect() frees it.
    core::mem::forget(inner);
    Ok(())
}

unsafe fn probe_hardware(inner: &mut Pctv320cxInner) -> Result {
    // Stage by stage: a single errno at the end of probe cannot tell a dead
    // I2C tunnel apart from a missing firmware file, and both look the same
    // in the boot log.
    if let Err(e) = inner.load_bridge_firmware() {
        kernel::pr_warn!("DiB0700 firmware download failed (errno {})\n", e.to_errno());
        return Err(e);
    }
    kernel::pr_info!("DiB0700 bridge microcontroller is running\n");
    if let Err(e) = inner.board_init() {
        kernel::pr_warn!("board init failed (errno {})\n", e.to_errno());
        return Err(e);
    }
    if let Err(e) = inner.decoder_setup() {
        kernel::pr_warn!("CX25843 bring-up failed (errno {})\n", e.to_errno());
        return Err(e);
    }
    inner.demod_release_bus();
    inner.decoder_ready = true;
    Ok(())
}

unsafe fn disconnect(intf: *mut bindings::usb_interface) {
    let cookie = bindings::pctv_dev_get_drvdata(&mut (*intf).dev as *mut bindings::device);
    if cookie.is_null() {
        return;
    }
    bindings::pctv_dev_set_drvdata(&mut (*intf).dev as *mut bindings::device, core::ptr::null_mut());

    let mut inner = KBox::<Pctv320cxInner>::from_raw(cookie as *mut Pctv320cxInner);
    let glue = inner.glue;
    if !glue.is_null() {
        bindings::pctv_glue_unregister(glue);
    }
    inner.free_urbs();
    if !glue.is_null() {
        bindings::pctv_glue_destroy(glue);
    }
}

/// Entry points called by the C `struct usb_driver`.
#[no_mangle]
extern "C" fn pctv320cx_probe(
    intf: *mut bindings::usb_interface,
    _id: *const bindings::usb_device_id,
) -> c_int {
    match unsafe { probe(intf) } {
        Ok(()) => 0,
        Err(e) => e.to_errno(),
    }
}

#[no_mangle]
extern "C" fn pctv320cx_disconnect(intf: *mut bindings::usb_interface) {
    unsafe { disconnect(intf) }
}

