/// Bytes in one whole BT.656 line as the bridge ships it: 4 sync + 1440
/// active + 284 blanking.  Verified against the captures in FINDINGS.md.
const LINE_BYTES: usize = 1728;
const SYNC_BYTES: usize = 4;
const ACTIVE_BYTES: usize = 1440;

/// Active lines per field, as the decoder emits them after trimming blanking.
/// PAL: 288, measured on hardware - every complete field in the mode-2
/// captures is exactly 288 lines (FINDINGS.md section 12.2).  NTSC: 243, the
/// 525-line half of cx25840_std_setup()'s vactive=487; not yet verified on
/// hardware.
const PAL_LINES: usize = 288;
const NTSC_LINES: usize = 243;

/// Bytes per active line kept in the frame: 720 pixels of UYVY (Cb Y Cr Y).
const ACTIVE_PIXEL_BYTES: usize = 1440;

/// Capture URBs in flight.  8 x 64 KiB covers ~1.5 frames of BT.656, which is
/// comfortably more than the 2 s videobuf2 timeout.
const NUM_URBS: usize = 8;
const URB_BYTES: usize = 65536;
/// Scratch holding one field's active lines (max PAL) before they are
/// vertically rescaled into the frame.  A field arrives with up to ~5% of its
/// lines missing (mode-2 bandwidth ceiling); writing the survivors directly
/// into their nominal rows makes every dropped line shift the rest of the
/// field up and the picture jitters.  The scratch lets the field end be found
/// first, then resamples the N captured lines onto the fixed 288-row grid.
const FIELD_SCRATCH_BYTES: usize = PAL_LINES * ACTIVE_PIXEL_BYTES;
/// Bulk-IN endpoint number that carries the analog capture stream (the
/// in-tree dib0700 devices table uses stream endpoint 2 for this card;
/// FINDINGS.md section 11.2: only 0x82 ever delivers).
const CAPTURE_EP_NUM: u8 = 2;
/// Staging buffer for the bulk-OUT writes.  The USB core refuses to DMA from
/// the stack (hcd.c: transfer buffer is on stack) and from the vmalloc'd
/// firmware blob, so every bulk-OUT payload is copied here first.  A firmware
/// record is at most 4 + 255 + 1 bytes.
const FW_BUF_BYTES: usize = 512;

// TV standard selector.  The C glue translates between v4l2_std_id and this;
// the card has no RF tuner, so it only picks the decoder's line/colour
// system.
const STD_PAL: u32 = 0;
const STD_NTSC: u32 = 1;

// Errnos, spelled out to keep the core independent of the kernel's error
// modules.
const EIO: c_int = 5;
const ENOMEM: c_int = 12;
const ENODEV: c_int = 19;
const EINVAL: c_int = 22;
const EOVERFLOW: c_int = 75;

// V4L2 control ids, mirrored here so the core does not depend on bindgen
// emitting the uapi macros.
const CID_BRIGHTNESS: u32 = 0x009a0902;
const CID_CONTRAST: u32 = 0x009a0903;
const CID_SATURATION: u32 = 0x009a0904;
const CID_HUE: u32 = 0x009a0905;

// videobuf2 buffer states are NOT mirrored here: the glue picks the state
// itself (pctv_glue_buffer_done() always completes with VB2_BUF_STATE_DONE)
// so the Rust side never has to know this kernel enum.  A hand-copied value
// is what broke the first streaming run (it was 0 = DEQUEUED, and
// vb2_buffer_done() then warned and returned the frames as ERROR).

