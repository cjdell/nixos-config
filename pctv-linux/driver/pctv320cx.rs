//!
//! pctv320cx - Pinnacle PCTV 320cx ExpressCard analog capture driver.
//!
//! The card is a DiB0700 USB bridge with a Conexant CX25843 video decoder and
//! a DiB7000P OFDM demodulator.  The vendor's Linux driver (dvb-usb/dib0700)
//! only drives the DVB-T side: the analog front end is reachable only through
//! the vendor's Windows driver, and the decoder is invisible to Linux because
//! the DiB0700 I2C tunnel is not exposed as an i2c_adapter.
//!
//! This driver drives the analog path natively:
//!
//!   - downloads the DiB0700 firmware (same blob the DVB driver uses) so the
//!     bridge's microcontroller runs,
//!   - talks to the CX25843 over the bridge's vendor I2C tunnel,
//!   - programs the decoder for composite / S-Video in PAL or NTSC,
//!   - arms the bridge and streams BT.656 8-bit video over bulk-IN,
//!   - deframes BT.656 into UYVY (Cb Y Cr Y) frames and hands them to videobuf2.
//!
//! The V4L2 face (struct video_device, struct vb2_queue, the ioctl table and
//! the control handler) lives in v4l2-glue.c, because those are embedded C
//! structs with function-pointer tables that the Rust V4L2 abstractions do not
//! cover.  The two halves meet in pctv320cx.h: the C glue calls the driver
//! through struct pctv_ops, the driver calls back through the
//! pctv_glue_buffer_*() handoff helpers.
//!
//! Hardware reverse-engineering notes: FINDINGS.md in this directory.

//! The kernel's own crates require an explicit `unsafe {}` around every unsafe
//! operation, even inside an `unsafe fn`.  This module opts out for the moment
//! to keep the bring-up code readable; tightening it up is a pre-upstream
//! cleanup item.
#![allow(unsafe_op_in_unsafe_fn)]

