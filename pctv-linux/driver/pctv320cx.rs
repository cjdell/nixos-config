/// Vendor control requests (drivers/media/usb/dvb-usb/dib0700.h).
///
/// bmRequestType must carry recipient=device (0x04): the vendor firmware
/// NACKs the recipient=0 form that the in-tree dib0700 driver sends, which is
/// why that driver never gets a reply off this card.
const REQTYPE_VENDOR_OUT: u8 = 0x44;
const REQTYPE_VENDOR_IN: u8 = 0xc4;

const RQ_SET_USB_XFER_LEN: u8 = 0x00;
const RQ_ENABLE_VIDEO: u8 = 0x0f;
const RQ_SET_I2C_PARAM: u8 = 0x10;
const RQ_NEW_I2C_READ: u8 = 0x12;
const RQ_NEW_I2C_WRITE: u8 = 0x13;
const RQ_GET_VERSION: u8 = 0x15;
const RQ_SET_CLOCK: u8 = 0x0b;
const RQ_SET_GPIO: u8 = 0x0c;

/// The 8-bit address the bridge answers I2C tunnel traffic at; the gate
/// control is a write to this pseudo-address.
const BRIDGE_I2C_ADDR: u8 = 0x40;

/// Bulk OUT endpoint 1 is the firmware download pipe.
const EP_FW_OUT: u8 = 0x01;

// V4L2 uapi values the Rust core needs.  They are #defines/enums in
// uapi/linux/videodev2.h that bindgen does not emit for this header; spelled
