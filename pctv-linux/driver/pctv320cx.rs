/// One capture URB, its DMA buffer, and the driver it belongs to.  The
/// parent pointer stays valid because the driver struct is pinned.
struct Urb {
    urb: *mut bindings::urb,
    buffer: *mut u8,
    /// DMA handle returned by usb_alloc_coherent() for @buffer.  It has to be
    /// the one handed to usb_free_coherent(), and it has to be written into
    /// the URB (URB_NO_TRANSFER_DMA_MAP) or the HCD maps the buffer a second
    /// time and leaves a different address in transfer_dma.
    dma: bindings::dma_addr_t,
    parent: *mut Pctv320cxInner,
}

impl Urb {
    const fn empty() -> Self {
        Self {
            urb: core::ptr::null_mut(),
            buffer: core::ptr::null_mut(),
            dma: 0,
            parent: core::ptr::null_mut(),
        }
    }
}


/// The driver.
///
/// `udev` is the raw `struct usb_device` behind the interface the shim handed
/// us; the interface itself is owned by the USB core for the lifetime of the
/// binding, which is exactly the lifetime of this object.
#[pin_data]
struct Pctv320cxInner {
    udev: *mut bindings::usb_device,
    intf: *mut bindings::usb_interface,
    glue: *mut bindings::pctv_glue,

    /// Bulk-IN endpoint actually advertised by the streaming interface.
    ep_in: u8,

    /// Capture URB pool.
    urbs: [Urb; NUM_URBS],

    /// DMA-safe staging buffer for the bulk-OUT writes (firmware records,
    /// jumpram).  Allocated with the URB pool, freed with it.
    fw_buf: *mut u8,

    /// Scratch for the field being deframed (see FIELD_SCRATCH_BYTES).
    /// Allocated with the URB pool, freed with it.
    field_buf: *mut u8,

    /// Streaming state, read by the URB completion (softirq) and written by
    /// start/stop (process context).
    streaming: Atomic<bool>,
    /// Set when a completion could not find a buffer to fill.
    dropped: Atomic<u32>,

    /// Deframer, shared by the URB completions.  Completions of different
    /// URBs may run on different CPUs, hence the spinlock.
    #[pin]
    deframer: SpinLock<Deframer>,

    /// Negotiated state.  Guarded by the video device lock held by the C glue
    /// for every ioctl, so no extra locking is needed for the ioctl path.
    std_sel: u32,
    input: u32,
    fmt: bindings::pctv_fmt,

    /// Decoder state we have to remember because CX25843 registers are
    /// write-only in places (clock/standard/enable).
    clock_on: bool,
    decoder_ready: bool,
}

// SAFETY: the fields are either plain data, or pointers into objects owned by
// the USB core / videobuf2 whose lifetime brackets this struct.  All mutation
// is serialised by the video device lock, except `streaming`/`dropped` which
// are atomic.
unsafe impl Send for Pctv320cxInner {}
unsafe impl Sync for Pctv320cxInner {}

