/// CX25843 register: video input mux.
const CX_REG_INPUT: u16 = 0x103;
/// CX25843 register: INPUT_MODE / OUTPUT_MODE / VBIT (cx25840_g/s_input()).
const CX_REG_INPUT_MODE: u16 = 0x401;
/// CX25843 picture controls, exactly as the in-tree cx25840 driver maps them
/// (cx25840_set_ctrl()): brightness 0x414 = val - 128, contrast 0x415 = val
/// << 1, saturation 0x420/0x421 = val << 1, hue 0x422 = val.
const CX_REG_BRIGHTNESS: u16 = 0x414;
const CX_REG_CONTRAST: u16 = 0x415;
const CX_REG_SATURATION: u16 = 0x420;
const CX_REG_SATURATION_U: u16 = 0x421;
const CX_REG_HUE: u16 = 0x422;
/// CX25843 registers: horizontal and vertical timing (cx25840_std_setup()).
const CX_REG_HBLANK: u16 = 0x470;
/// CX25843 register: standard select (0x49f).
const CX_REG_STD: u16 = 0x49f;
/// CX25843 registers: status (0x40d/0x40e: bit 0x20 of 0x40e = signal detect).
const CX_REG_STATUS_A: u16 = 0x40d;
const CX_REG_STATUS_B: u16 = 0x40e;
const CX_STATUS_SIGNAL: u8 = 0x20;
/// CX25843 registers: parallel video output enable (0x115/0x116).
const CX_REG_OUT_A: u16 = 0x115;
const CX_REG_OUT_B: u16 = 0x116;
/// CX25843 microcontroller: firmware data window and control.
const CX_REG_FW_DATA: u16 = 0x802;
const CX_REG_FW_COUNT_LO: u16 = 0x800;
const CX_REG_FW_COUNT_HI: u16 = 0x801;
const CX_REG_CR: u16 = 0x803;
const CX_CR_RESET: u8 = 0x0b;
const CX_CR_RUN: u8 = 0x03;
const CX_CR_INT_ENABLE: u8 = 0x10;

/// Per-standard timing, from cx25840_std_setup().
struct StdTiming {
    std_reg: u8,
    hblank: u16,
    hactive: u16,
    burst: u8,
    vblank: u16,
    vactive: u16,
    vblank656: u8,
    subcarrier: u32,
    comb: u8,
    luma_lpf: u8,
    uv_lpf: u8,
}

const TIMING_PAL: StdTiming = StdTiming {
    std_reg: 0x11,
    hblank: 132,
    hactive: 720,
    burst: 93,
    vblank: 36,
    vactive: 580,
    vblank656: 40,
    subcarrier: 688739,
    comb: 0x20,
    luma_lpf: 2,
    uv_lpf: 1,
};

const TIMING_NTSC: StdTiming = StdTiming {
    std_reg: 0x14,
    hblank: 122,
    hactive: 720,
    burst: 0x5b,
    vblank: 26,
    vactive: 487,
    vblank656: 26,
    subcarrier: 556063,
    comb: 0x66,
    luma_lpf: 1,
    uv_lpf: 1,
};

/// One input: the CX25843 mux value (reg 0x103) that selects it.  S-Video
/// feeds luma and chroma into two decoder inputs; the mux value is all that
/// has to change - 0x401 stays at 0xc0, which is what the on-hardware
/// S-Video captures used (FINDINGS.md section 12.1).
struct InputDef {
    mux: u8,
}

/// Video1 / Video2 / Video3 are the three decoder inputs the card's dongle
/// wires up; S-Video feeds luma and chroma into two of them.
const INPUTS: [InputDef; 4] = [
    InputDef { mux: 0xf0 }, // composite, Video1
    InputDef { mux: 0xf1 }, // composite, Video2
    InputDef { mux: 0xf2 }, // composite, Video3
    InputDef { mux: 0xd0 },  // S-Video (Video2 + Video3)
];

impl Pctv320cxInner {
    /// Read-modify-write a CX25843 register.
    unsafe fn cx_or(&self, reg: u16, mask: u8, val: u8) -> c_int {
        let cur = self.cx_r(reg);
        if cur < 0 {
            return cur;
        }
        self.cx_w(reg, ((cur as u8) & mask) | val)
    }

    /// Load the decoder's microcode through the bridge's I2C tunnel.  The
    /// blob is streamed into the 0x802 window in 46-byte bursts.
    unsafe fn load_decoder_firmware(&self) -> Result {
        let dev = &mut (*self.intf).dev as *mut bindings::device;
        let fw = bindings::pctv_request_fw(dev, DECODER_FIRMWARE.as_char_ptr() as *const i8);
        if fw.is_null() {
            return Err(Error::from_errno(-ENODEV));
        }
        let blob =
            unsafe { core::slice::from_raw_parts((*fw).data, (*fw).size as usize) };

        // Halt the microcontroller, poke the standard reset sequence, then
        // feed the image.
        let cr = self.cx_r(CX_REG_CR);
        if cr >= 0 {
            self.cx_w(CX_REG_CR, (cr as u8) & !CX_CR_INT_ENABLE);
        }
        self.cx_w(0x000, 0x04);
        self.cx_w(0x159, 0x23);
        self.cx_w(0x15a, 0x87);
        self.cx_w(0x15b, 0x06);
        udelay(time::Delta::from_micros(10));
        self.cx_w(0x159, 0xe1);
        udelay(time::Delta::from_micros(10));
        self.cx_w(0x15a, 0x86);
        self.cx_w(0x159, 0xe0);
        self.cx_w(0x159, 0xe1);
        self.cx_w(0x15b, 0x10);
        self.cx_w(0x15d, 0xe3);
        self.cx_w(0x15e, 0x86);
        self.cx_w(0x15f, 0x06);
        udelay(time::Delta::from_micros(10));
        self.cx_w(0x15d, 0xe1);
        self.cx_w(0x15d, 0xe0);
        self.cx_w(0x15d, 0xe1);
        self.cx_w(0x136, 0x0a);
        self.cx_w(0x13c, 0x01);
        self.cx_w(0x13c, 0x00);

        self.cx_w(CX_REG_FW_COUNT_LO, 0);
        self.cx_w(CX_REG_FW_COUNT_HI, 0);
        self.cx_w(CX_REG_CR, CX_CR_RESET);
        self.cx_w(0x000, 0x20);

        let mut off = 0usize;
        while off < blob.len() {
            let len = core::cmp::min(blob.len() - off, 46);
            if self.cx_burst(CX_REG_FW_DATA, &blob[off..off + len]) < 0 {
                bindings::pctv_release_fw(dev, fw);
                return Err(Error::from_errno(-EIO));
            }
            off += len;
        }

        self.cx_w(0x000, 0);
        self.cx_w(CX_REG_CR, CX_CR_RUN);

        // The decoder counts the bytes it took; a mismatch means the image
        // stalled and the decoder will not lock.
        let lo = self.cx_r(CX_REG_FW_COUNT_LO);
        let hi = self.cx_r(CX_REG_FW_COUNT_HI);
        bindings::pctv_release_fw(dev, fw);
        if lo < 0 || hi < 0 || (((hi as u32) << 8) | (lo as u32)) != blob.len() as u32 {
            return Err(Error::from_errno(-EIO));
        }
        Ok(())
    }
}

impl Pctv320cxInner {
    /// The decoder registers that must be set once its microcode is running:
    /// parallel output on, VBI/teletext windows cleared.
    unsafe fn decoder_post_firmware(&self) {
        self.cx_w(0x115, 0x8c);
        self.cx_w(0x116, 0x07);
        self.cx_w(0x118, 0x02);
        self.cx_w(0x4a5, 0x80);
        self.cx_w(0x4a5, 0x00);
        self.cx_w(0x402, 0x00);
        self.cx_or(0x4a2, !0x10, 0x10);
        self.cx_w(0x8d3, 0x1f);
        self.cx_w(0x8e3, 0x03);
        self.cx_w(0x914, 0xa0);
        self.cx_w(0x918, 0xa0);
        self.cx_w(0x919, 0x01);
        self.cx_w(0x809, 0x04);
        self.cx_w(0x8cf, 0x0f);
        self.cx_or(CX_REG_CR, !CX_CR_INT_ENABLE, CX_CR_INT_ENABLE);
    }

    /// Program the decoder for one TV standard (cx25840_std_setup()).
    unsafe fn std_setup(&self, std_sel: u32) {
        let t = if std_sel == STD_NTSC {
            &TIMING_NTSC
        } else {
            &TIMING_PAL
        };

        self.cx_w(CX_REG_STD, t.std_reg);
        self.cx_w(CX_REG_HBLANK, t.hblank as u8);
        self.cx_w(
            CX_REG_HBLANK + 1,
            ((((t.hblank >> 8) & 3) | (t.hactive << 4)) & 0xff) as u8,
        );
        self.cx_w(CX_REG_HBLANK + 2, (t.hactive >> 4) as u8);
        self.cx_w(CX_REG_HBLANK + 3, t.burst);
        self.cx_w(CX_REG_HBLANK + 4, t.vblank as u8);
        self.cx_w(
            CX_REG_HBLANK + 5,
            ((((t.vblank >> 8) & 3) | (t.vactive << 4)) & 0xff) as u8,
        );
        self.cx_w(CX_REG_HBLANK + 6, (t.vactive >> 4) as u8);
        self.cx_w(CX_REG_HBLANK + 7, t.vblank656);
        self.cx_w(CX_REG_HBLANK + 8, 0x1f);
        self.cx_w(CX_REG_HBLANK + 9, 0x02);
        self.cx_w(CX_REG_HBLANK + 10, (t.luma_lpf << 6) | ((t.uv_lpf << 4) & 0x30));
        self.cx_w(CX_REG_HBLANK + 11, t.comb);
        self.cx_w(CX_REG_HBLANK + 12, (t.subcarrier & 0xff) as u8);
        self.cx_w(CX_REG_HBLANK + 13, ((t.subcarrier >> 8) & 0xff) as u8);
        self.cx_w(CX_REG_HBLANK + 14, ((t.subcarrier >> 16) & 0xff) as u8);
        // 0x47f: PAL/NTSC chroma band selection.
        self.cx_w(CX_REG_HBLANK + 15, if std_sel == STD_NTSC { 0x00 } else { 0x01 });

        // Keep the parallel video output to the bridge enabled.
        let a = self.cx_r(CX_REG_OUT_A);
        if a >= 0 {
            self.cx_w(CX_REG_OUT_A, (a as u8) | 0x0c);
        }
        let b = self.cx_r(CX_REG_OUT_B);
        if b >= 0 {
            self.cx_w(CX_REG_OUT_B, (b as u8) | 0x04);
        }
    }

    /// Select composite or S-Video (cx25840_g/s_input()).
    unsafe fn input_setup(&self, input: u32) {
        let def = match INPUTS.get(input as usize) {
            Some(d) => d,
            None => return,
        };
        self.cx_w(CX_REG_INPUT, def.mux);
        // 0x401: bit 7 CAGCEN on, bit 6 CKILLEN.  The vendor init leaves this
        // at 0x60, which pins the chroma path: every even byte of the BT.656
        // stream comes back as exactly 0x80 (FINDINGS.md section 9).  0xc0 is
        // the value that makes Cb/Cr carry signal, verified on hardware for
        // both composite and S-Video.
        self.cx_w(CX_REG_INPUT_MODE, 0xc0);
    }

    /// Apply one V4L2 control to the decoder.  The CX25843 ranges are the
    /// ones the in-tree driver uses: brightness 0..255 (0x80 = 1.0),
    /// contrast/saturation 0..127 (0x40 = 1.0), hue -128..127.
    unsafe fn ctrl_apply(&self, id: u32, value: c_int) -> c_int {
        match id {
            CID_BRIGHTNESS => self.cx_w(CX_REG_BRIGHTNESS, (value - 128) as u8),
            CID_CONTRAST => self.cx_w(CX_REG_CONTRAST, ((value << 1) & 0xff) as u8),
            CID_SATURATION => {
                let v = ((value << 1) & 0xff) as u8;
                self.cx_w(CX_REG_SATURATION, v);
                self.cx_w(CX_REG_SATURATION_U, v)
            }
            CID_HUE => self.cx_w(CX_REG_HUE, (value & 0xff) as u8),
            _ => -EINVAL,
        }
    }

    /// Is there a video signal on the selected input?  Bit 0x20 of 0x40e is
    /// the signal-detect flag; it needs the colour killer settled, so the
    /// caller polls it rather than reading once.
    unsafe fn signal_present(&self) -> bool {
        let v = self.cx_r(CX_REG_STATUS_B);
        v >= 0 && ((v as u8) & CX_STATUS_SIGNAL) != 0
    }

    /// Log the decoder's lock state (0x40d = detected format, 0x40e bit 0x20
    /// = video signal present).  0x40e only settles once the colour killer
    /// has made up its mind, so poll briefly before reporting.  Without a
    /// lock the bridge has nothing to stream - a locked state is a
    /// prerequisite for frames, and the input connector on these cards is
    /// known to be intermittent (FINDINGS.md section 10).
    unsafe fn log_signal_state(&self, stage: &str) -> bool {
        let mut a = 0;
        let mut b = 0;
        let mut locked = false;
        for _ in 0..10 {
            a = self.cx_r(CX_REG_STATUS_A);
            b = self.cx_r(CX_REG_STATUS_B);
            locked = b >= 0 && ((b as u8) & CX_STATUS_SIGNAL) != 0;
            if locked {
                break;
            }
            fsleep(time::Delta::from_millis(20));
        }
        if a < 0 || b < 0 {
            kernel::pr_warn!(
                "signal check ({}): decoder did not answer (0x40d errno {}, 0x40e errno {})\n",
                stage,
                a,
                b
            );
            return false;
        }
        if locked {
            kernel::pr_info!(
                "signal check ({}): 0x40d = 0x{:02x} 0x40e = 0x{:02x} -> LOCKED\n",
                stage,
                a as u8,
                b as u8
            );
        } else {
            kernel::pr_warn!(
                "signal check ({}): 0x40d = 0x{:02x} 0x40e = 0x{:02x} -> NO SIGNAL (capture will be empty)\n",
                stage,
                a as u8,
                b as u8
            );
        }
        locked
    }

    /// The DiB7000P demod shares the bridge's 8-bit parallel bus with the
    /// decoder.  Unless its output drivers are tri-stated the two drivers
    /// fight over the bus and nothing reaches the FIFO: this is the one step
    /// the vendor's Windows driver does that the DVB driver never has to.
    unsafe fn demod_release_bus(&self) {
        self.demod_w(1286, 0x0000);
        self.demod_w(1287, 0x0003);
        self.demod_w(235, 0x0022);
        self.demod_w(236, 1792);
    }

    /// 16-bit register write to the demod over the same I2C tunnel.
    unsafe fn demod_w(&self, reg: u16, val: u16) {
        let _ = self.i2c_write(
            DEMOD_I2C_ADDR,
            &[
                (reg >> 8) as u8,
                (reg & 0xff) as u8,
                (val >> 8) as u8,
                (val & 0xff) as u8,
            ],
        );
    }

    /// Full decoder bring-up: microcode, standard, input, controls.
    unsafe fn decoder_setup(&self) -> Result {
        let id = self.cx_r(0x100);
        if id < 0 {
            kernel::pr_warn!("CX25843 did not answer the I2C tunnel (reg 0x100: errno {})\n", id);
        } else {
            kernel::pr_info!("CX25843 chip id (reg 0x100) = 0x{:02x}\n", id);
        }
        if id != 0x34 {
            kernel::pr_warn!("CX25843 not detected (reg 0x100 = 0x{:02x})\n", id);
        } else {
            // 0x34 is the CX25843 chip id: the part is there, so (re)load the
            // microcode and program the post-firmware registers.  The
            // microcode lives in RAM and is lost on power-cycle, so this runs
            // on every probe (same as the in-tree cx25840 driver).
            self.load_decoder_firmware()?;
            self.decoder_post_firmware();
        }
        self.std_setup(self.std_sel);
        self.input_setup(self.input);
        self.log_signal_state("bring-up");
        Ok(())
    }
}

