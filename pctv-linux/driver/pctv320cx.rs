impl Pctv320cxInner {
    /// Allocate the capture URBs and their coherent buffers.
    unsafe fn alloc_urbs(&mut self) -> Result {
        if self.fw_buf.is_null() {
            self.fw_buf = bindings::pctv_kmalloc(FW_BUF_BYTES) as *mut u8;
            if self.fw_buf.is_null() {
                return Err(Error::from_errno(-ENOMEM));
            }
        }
        if self.field_buf.is_null() {
            self.field_buf = bindings::pctv_vmalloc(FIELD_SCRATCH_BYTES) as *mut u8;
            if self.field_buf.is_null() {
                return Err(Error::from_errno(-ENOMEM));
            }
        }
        for i in 0..NUM_URBS {
            let urb = bindings::usb_alloc_urb(0, bindings::pctv_gfp_kernel());
            if urb.is_null() {
                return Err(Error::from_errno(-ENOMEM));
            }
            let mut dma = 0u64;
            let buffer = bindings::usb_alloc_coherent(
                self.udev,
                URB_BYTES,
                bindings::pctv_gfp_kernel(),
                &mut dma as *mut u64 as *mut bindings::dma_addr_t,
            ) as *mut u8;
            if buffer.is_null() {
                bindings::usb_free_urb(urb);
                return Err(Error::from_errno(-ENOMEM));
            }
            self.urbs[i] = Urb {
                urb,
                buffer,
                dma: dma as bindings::dma_addr_t,
                parent: core::ptr::null_mut(),
            };
        }
        Ok(())
    }

    unsafe fn free_urbs(&mut self) {
        for u in self.urbs.iter_mut() {
            if u.urb.is_null() {
                continue;
            }
            bindings::usb_kill_urb(u.urb);
            if !u.buffer.is_null() {
                bindings::usb_free_coherent(
                    self.udev,
                    URB_BYTES,
                    u.buffer as *mut c_void,
                    u.dma,
                );
                u.buffer = core::ptr::null_mut();
            }
            bindings::usb_free_urb(u.urb);
            u.urb = core::ptr::null_mut();
        }
        if !self.fw_buf.is_null() {
            bindings::pctv_kfree(self.fw_buf as *mut c_void);
            self.fw_buf = core::ptr::null_mut();
        }
        if !self.field_buf.is_null() {
            bindings::pctv_vfree(self.field_buf as *const c_void);
            self.field_buf = core::ptr::null_mut();
        }
    }

    /// Arm the bridge and submit the capture URBs.
    unsafe fn stream_start(&mut self) -> c_int {
        // ANALOG framing, MODE 2 (0x12): whole BT.656 lines (1728 bytes) at
        // ~25.6 MB/s.  Mode 1 (0x11, what the vendor/kernel use) delivers only
        // the active part of each line and cannot sustain PAL; mode 0 (0x10)
        // runs the data through the TS multiplexer and yields no BT.656 at
        // all.  See FINDINGS.md section 11.
        self.release_channels();
        if !self.log_signal_state("stream-start") {
            kernel::pr_warn!("arming the bridge anyway, but no signal is locked\n");
        }
        if self.enable_video(0x12) < 0 {
            return -EIO;
        }
        self.set_usb_transfer_length(0);

        self.deframer.lock().reset(self.std_sel);
        self.streaming.store(true, Relaxed);

        let mut submitted = 0;
        for i in 0..NUM_URBS {
            let pipe = bindings::pctv_usb_rcvbulkpipe(self.udev, self.ep_in);
            self.urbs[i].parent = self as *mut Pctv320cxInner;
            let (urb, buffer) = (self.urbs[i].urb, self.urbs[i].buffer);
            let ctx = &mut self.urbs[i] as *mut Urb;
            bindings::pctv_usb_fill_bulk_urb(
                urb,
                self.udev,
                pipe,
                buffer as *mut c_void,
                URB_BYTES as c_int,
                Some(Pctv320cxInner::urb_complete),
                ctx as *mut c_void,
            );
            bindings::pctv_urb_use_coherent(urb, self.urbs[i].dma);
            if bindings::usb_submit_urb(urb, bindings::pctv_gfp_kernel()) < 0 {
                break;
            }
            submitted += 1;
        }
        if submitted == 0 {
            self.stream_stop();
            return -EIO;
        }
        kernel::pr_info!(
            "streaming on endpoint 0x{:02x}: {} URBs submitted\n",
            self.ep_in,
            submitted
        );
        0
    }

    /// Unarm the bridge and reap the capture URBs.
    unsafe fn stream_stop(&mut self) {
        self.streaming.store(false, Relaxed);
        for u in self.urbs.iter() {
            if !u.urb.is_null() {
                bindings::usb_kill_urb(u.urb);
            }
        }
        // 0x0f/0x00: streaming off.
        self.enable_video(0x00);

        // If the deframer was halfway through a buffer, hand it back to
        // videobuf2 in QUEUED state - otherwise it stays ACTIVE forever and
        // videobuf2 warns ("stop_streaming operation is leaving buffer N in
        // active state") and the buffer leaks.
        let mut d = self.deframer.lock();
        if !d.vb.is_null() {
            bindings::pctv_glue_buffer_requeue(self.glue, d.vb);
            d.vb = core::ptr::null_mut();
            d.addr = core::ptr::null_mut();
        }
    }

    /// Bulk-IN completion (softirq context).
    unsafe extern "C" fn urb_complete(urb: *mut bindings::urb) {
        let ctx = (*urb).context as *mut Urb;
        if ctx.is_null() {
            return;
        }
        let p = (*ctx).parent;
        if p.is_null() {
            return;
        }

        let status = (*urb).status;
        let actual = (*urb).actual_length;
        if (*p).streaming.load(Relaxed) {
            if status == 0 && actual > 0 {
                let data = core::slice::from_raw_parts((*ctx).buffer, actual as usize);
                let mut guard = (*p).deframer.lock();
                Self::deframe((*p).glue, &(*p).dropped, &mut *guard, data, (*p).field_buf);
            } else if status != 0 {
                // A halt on the pipe (the device dropped FIFO data) or a
                // short transfer: count it, the next submit clears the halt.
                (*p).dropped.fetch_add(1, Relaxed);
            }
            // Keep the pipe running.
            bindings::usb_submit_urb(urb, bindings::pctv_gfp_atomic());
        }
    }
}

